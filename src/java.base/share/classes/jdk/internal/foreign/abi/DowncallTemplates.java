package jdk.internal.foreign.abi;

import jdk.internal.foreign.CABI;
import jdk.internal.util.OperatingSystem;
import jdk.internal.util.StaticProperty;
import java.io.*;
import java.lang.foreign.*;
import java.lang.invoke.MethodType;
import java.util.*;
import java.util.zip.CRC32;

/** Selects build-generated bytes for an exact downcall recipe. */
final class DowncallTemplates {
    static final int MAGIC=0x46464d54,FORMAT=1;
    static final String RESOURCE="templates/scalar-int.bin";
    record Entry(String platform,String architecture,int[][][] input,int[][][] output,int[][][] volatiles,
                 int stackAlignment,int shadowSpace,int[] scratch1,int[] scratch2,int[] target,int[] retbuf,int[] capture,
                 int[] argStore,int[] returnLoad) {}
    static String platform() {
        String arch=StaticProperty.osArch();
        if(OperatingSystem.current()!=OperatingSystem.LINUX||java.nio.ByteOrder.nativeOrder()!=java.nio.ByteOrder.LITTLE_ENDIAN)return "unsupported";
        if((arch.equals("amd64")||arch.equals("x86_64"))&&CABI.current()==CABI.SYS_V)return "linux-x64-sysv";
        if(arch.equals("aarch64")&&CABI.current()==CABI.LINUX_AARCH_64)return "linux-aarch64";
        return "unsupported";
    }
    static boolean storage(VMStorage actual,int[] expected) {
        return expected==null?actual==null:actual!=null&&actual.type()==expected[0]&&
            actual.segmentMaskOrSize()==expected[1]&&actual.indexOrOffset()==expected[2];
    }
    static boolean matrix(VMStorage[][] actual,int[][][] expected) {
        if(actual.length!=expected.length)return false;
        for(int i=0;i<actual.length;i++) {
            if(actual[i].length!=expected[i].length)return false;
            for(int j=0;j<actual[i].length;j++)if(!storage(actual[i][j],expected[i][j]))return false;
        }
        return true;
    }
    private static boolean matchesRecipe(CallingSequence cs,MethodType leaf,MethodType caller) {
        if(!cs.forDowncall()||!cs.hasEmptyLinkerOptions()||cs.needsReturnBuffer()||cs.returnBufferSize()!=0||
           cs.allocationSize()!=0||cs.capturedStateMask()!=0||!cs.needsTransition()||
           cs.usingAddressPairs()||cs.numLeadingParams()!=2)return false;
        MethodType expectedLeaf=MethodType.methodType(int.class,long.class,int.class);
        MethodType expectedCaller=MethodType.methodType(int.class,SegmentAllocator.class,MemorySegment.class,int.class);
        if(!leaf.equals(expectedLeaf)||!cs.calleeMethodType().equals(expectedLeaf)||!caller.equals(expectedCaller)||
           !cs.callerMethodType().equals(expectedCaller.dropParameterTypes(0,1)))return false;
        if(!cs.functionDesc().equals(FunctionDescriptor.of(ValueLayout.JAVA_INT,ValueLayout.ADDRESS,ValueLayout.JAVA_INT)))return false;
        if(cs.argumentBindingsCount()!=2)return false;
        var symbol=cs.argumentBindings(0);var arg=cs.argumentBindings(1);var result=cs.returnBindings();
        return symbol.size()==2&&symbol.get(0) instanceof Binding.SegmentOffset s&&!s.allowHeap()&&
            symbol.get(1) instanceof Binding.VMStore m&&m.type()==long.class&&
            arg.size()==1&&arg.get(0) instanceof Binding.VMStore a&&a.type()==int.class&&
            result.size()==1&&result.get(0) instanceof Binding.VMLoad r&&r.type()==int.class;
    }
    private static boolean matchesEntry(Entry e,String platform,ABIDescriptor abi,CallingSequence cs) {
        if(!e.platform().equals(platform)||!e.architecture().equals(abi.arch.getClass().getName()))return false;
        if(!matrix(abi.inputStorage,e.input())||!matrix(abi.outputStorage,e.output())||!matrix(abi.volatileStorage,e.volatiles())||
           abi.stackAlignment!=e.stackAlignment()||abi.shadowSpace!=e.shadowSpace()||!storage(abi.scratch1,e.scratch1())||
           !storage(abi.scratch2,e.scratch2())||!storage(abi.targetAddrStorage,e.target())||
           !storage(abi.retBufAddrStorage,e.retbuf())||!storage(abi.capturedStateStorage,e.capture()))return false;
        return storage(((Binding.VMStore)cs.argumentBindings(0).get(1)).storage(),e.target())&&
            storage(((Binding.VMStore)cs.argumentBindings(1).get(0)).storage(),e.argStore())&&
            storage(((Binding.VMLoad)cs.returnBindings().get(0)).storage(),e.returnLoad());
    }
    static boolean matches(Entry e,String platform,ABIDescriptor abi,CallingSequence cs,MethodType leaf,MethodType caller) {
        return matchesRecipe(cs,leaf,caller)&&matchesEntry(e,platform,abi,cs);
    }
    static byte[] decode(InputStream input,String sourceId,int major,int expectedLength,long crc) throws IOException {
        if(input==null)return null;
        try(var in=new DataInputStream(input)) {
            if(in.readInt()!=MAGIC||in.readInt()!=FORMAT||in.readInt()!=major||!in.readUTF().equals(sourceId))return null;
            int length=in.readInt();if(length!=expectedLength||length>8192)return null;
            byte[] bytes=in.readNBytes(length);
            if(bytes.length!=length||in.read()!=-1||length<8)return null;
            int version=(Byte.toUnsignedInt(bytes[6])<<8)|Byte.toUnsignedInt(bytes[7]);
            if(version!=major||bytes[0]!=(byte)0xca||bytes[1]!=(byte)0xfe||bytes[2]!=(byte)0xba||bytes[3]!=(byte)0xbe)return null;
            CRC32 check=new CRC32();check.update(bytes);return check.getValue()==crc?bytes:null;
        }
    }
    static byte[] lookup(String sourceId,int major,boolean defaultConfiguration,ABIDescriptor abi,CallingSequence cs,MethodType leaf,MethodType caller) {
        // This is computed from BindingSpecializer's effective frozen fields.
        // Reading mutable system properties here would disagree with the emitter.
        if(!defaultConfiguration) {
            return null;
        }
        String platform=platform();
        // Most downcalls cannot use this recipe. Reject them before loading
        // generated metadata or walking an ABI's register-storage tables.
        if(platform.equals("unsupported")||!matchesRecipe(cs,leaf,caller)) {
            return null;
        }
        for(Entry e:GeneratedDowncallTemplateData.ENTRIES) {
            if(matchesEntry(e,platform,abi,cs)) {
                try {
                    byte[] bytes=decode(GeneratedDowncallTemplateData.open(),sourceId,major,
                        GeneratedDowncallTemplateData.length(),GeneratedDowncallTemplateData.crc());
                    if(bytes!=null){return bytes;}
                } catch(IOException ignored) { /* Missing/truncated image resource uses normal generation. */ }
                break;
            }
        }
        return null;
    }
}
