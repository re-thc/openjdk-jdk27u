package org.openjdk.bench.vm.compiler;

import java.util.concurrent.TimeUnit;
import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Fork;
import org.openjdk.jmh.annotations.Measurement;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Scope;
import org.openjdk.jmh.annotations.State;
import org.openjdk.jmh.annotations.Warmup;

@State(Scope.Thread)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Warmup(iterations = 3, time = 1)
@Measurement(iterations = 5, time = 1)
@Fork(3)
public class CommonScalarIntrinsics {
    private long x = 0x923456789abcdef0L;
    private long y = 0x13579bdf02468aceL;

    @Benchmark
    public int leadingZeros() {
        return Long.numberOfLeadingZeros(x);
    }

    @Benchmark
    public int bitCount() {
        return Long.bitCount(x);
    }

    @Benchmark
    public long reverseBits() {
        return Long.reverse(x);
    }

    @Benchmark
    public long multiplyHigh() {
        return Math.multiplyHigh(x, y);
    }

    @Benchmark
    public long unsignedDivide() {
        return Long.divideUnsigned(x, y);
    }

    @Benchmark
    public long addExact() {
        return Math.addExact(x, y);
    }
}
