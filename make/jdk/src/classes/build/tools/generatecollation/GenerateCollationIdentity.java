package build.tools.generatecollation;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.HexFormat;
import java.util.TreeSet;
import java.util.stream.Stream;

/** Bind collation resources to a reproducible, conservative target input set. */
public final class GenerateCollationIdentity {
    private static final String BASE = "src/java.base/share/classes/";
    private static final String LD = "src/jdk.localedata/share/classes/";

    public static void main(String[] args) throws Exception {
        if (args.length != 3) {
            throw new IllegalArgumentException("topdir generated-java-file metadata-directory");
        }
        Path root = Path.of(args[0]).toAbsolutePath().normalize();
        Path generated = Path.of(args[1]);
        Path metadata = Path.of(args[2]);
        TreeSet<String> inputs = new TreeSet<>();
        for (String directory : new String[] {
                BASE + "java/text", BASE + "jdk/internal/icu", BASE + "sun/text",
                BASE + "jdk/internal/access", LD + "sun/text/resources/ext",
                "src/java.base/share/data/unicodedata",
                "make/jdk/src/classes/build/tools/generatecharacter",
                "make/jdk/src/classes/build/tools/generatecollation"}) {
            try (Stream<Path> files = Files.walk(root.resolve(directory))) {
                files.filter(Files::isRegularFile).forEach(path -> inputs.add(relative(root, path)));
            }
        }
        try (Stream<Path> files = Files.list(root.resolve(BASE + "java/lang"))) {
            files.filter(Files::isRegularFile)
                 .filter(path -> path.getFileName().toString().startsWith("Character"))
                 .forEach(path -> inputs.add(relative(root, path)));
        }
        for (String file : new String[] {
                BASE + "sun/util/locale/provider/CollationRules.java",
                BASE + "sun/util/locale/provider/CollatorProviderImpl.java",
                "make/common/CollationData.gmk", "make/Main.gmk", "make/ToolsJdk.gmk",
                "make/modules/java.base/Gensrc.gmk", "make/modules/java.base/Gendata.gmk",
                "make/modules/java.base/gensrc/GensrcCharacterData.gmk",
                "make/modules/java.base/gensrc/GensrcCollationData.gmk",
                "make/modules/java.base/gendata/GendataCollationData.gmk",
                "make/modules/jdk.localedata/Gendata.gmk"}) {
            if (!Files.isRegularFile(root.resolve(file))) {
                throw new IOException("Missing target collation input: " + file);
            }
            inputs.add(file);
        }
        StringBuilder manifest = new StringBuilder("schema=2\nunicode=17.0.0\n");
        for (String name : inputs) {
            manifest.append(hash(Files.readAllBytes(root.resolve(name))))
                    .append("  ").append(name).append('\n');
        }
        String identity = hash(manifest.toString().getBytes(StandardCharsets.UTF_8));
        String source = "// Generated by GenerateCollationIdentity. Do not edit.\n"
                + "package sun.text.resources;\n\n"
                + "public final class CollationDataIdentity {\n"
                + "    private CollationDataIdentity() {}\n"
                + "    public static final String INPUTS_SHA256 = \"" + identity + "\";\n"
                + "}\n";
        TreeSet<String> bundles = new TreeSet<>();
        for (String prefix : new String[] {BASE + "sun/text/resources/", LD + "sun/text/resources/ext/"}) {
            try (Stream<Path> files = Files.list(root.resolve(prefix))) {
                files.filter(Files::isRegularFile).forEach(path -> {
                    String name = path.getFileName().toString();
                    if (name.startsWith("CollationData") && name.endsWith(".java")
                            && !name.equals("CollationDataProvider.java")) {
                        String relative = relative(root, path);
                        String modulePrefix = relative.startsWith(BASE) ? BASE : LD;
                        bundles.add(relative.substring(modulePrefix.length(), relative.length() - 5)
                                .replace('/', '.'));
                    }
                });
            }
        }
        Files.createDirectories(metadata);
        writeIfChanged(metadata.resolve("sources.sha256"), manifest.toString());
        writeIfChanged(metadata.resolve("bundles.txt"), String.join("\n", bundles) + "\n");
        Files.createDirectories(generated.toAbsolutePath().getParent());
        writeIfChanged(generated, source);
        System.out.println("Collation target inputs: " + inputs.size() + " SHA-256 " + identity);
    }

    private static String relative(Path root, Path file) {
        return root.relativize(file).toString().replace(file.getFileSystem().getSeparator(), "/");
    }

    private static String hash(byte[] bytes) throws Exception {
        return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes));
    }

    private static void writeIfChanged(Path target, String text) throws IOException {
        byte[] bytes = text.getBytes(StandardCharsets.UTF_8);
        if (!Files.exists(target) || !java.util.Arrays.equals(Files.readAllBytes(target), bytes)) {
            Files.write(target, bytes);
        }
    }
}
