package build.tools.serializer;

import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.HexFormat;
import java.util.PropertyResourceBundle;

/**
 * Regenerates CharInfoData from the two bundled properties files. Run with the
 * serializer source directory and output file as arguments. The order is the
 * PropertyResourceBundle enumeration order, not sorted character/name order:
 * changing it can change the resulting HashMap's collision chains and aliases.
 */
public final class GenerateCharInfo {
    public static void main(String[] args) throws Exception {
        if (args.length != 2) {
            throw new IllegalArgumentException("serializer-directory output-file");
        }
        Path directory = Path.of(args[0]);
        String header = Files.readString(directory.resolve("CharInfo.java"));
        header = header.substring(0, header.indexOf("package "));
        StringBuilder out = new StringBuilder(header);
        out.append("package com.sun.org.apache.xml.internal.serializer;\n\n")
           .append("// Generated by build.tools.serializer.GenerateCharInfo. Do not edit.\n")
           .append("// Immutable literals only; CharInfo owns all mutable maps and masks.\n")
           .append("final class CharInfoData {\n")
           .append("    static String entities(boolean html) {\n")
           .append("        return html ? HTML.entities() : XML.entities();\n    }\n")
           .append("    static String bits(boolean html) {\n")
           .append("        return html ? HTML.bits() : XML.bits();\n    }\n")
           .append("    static String ascii(boolean html) {\n")
           .append("        return html ? HTML.ascii() : XML.ascii();\n    }\n")
           .append("    static boolean onlyQuotAmpLtGt(boolean html) {\n")
           .append("        return html ? HTML.onlyQuotAmpLtGt() : XML.onlyQuotAmpLtGt();\n    }\n");
        for (String kind : new String[] {"XML", "HTML"}) {
            byte[] bytes = Files.readAllBytes(directory.resolve(kind + "Entities.properties"));
            PropertyResourceBundle bundle;
            try (var in = new java.io.ByteArrayInputStream(bytes)) {
                bundle = new PropertyResourceBundle(in);
            }
            StringBuilder entities = new StringBuilder();
            boolean[] special = new boolean[65536];
            boolean noExtra = true;
            var keys = bundle.getKeys();
            while (keys.hasMoreElements()) {
                String name = keys.nextElement();
                int code = Integer.parseInt(bundle.getString(name));
                if (code < 0 || code > 65535 || name.indexOf(';') >= 0) {
                    throw new IllegalArgumentException("Unsupported bundled entity: " + name);
                }
                entities.append((char) code).append('&').append(name).append(';');
                special[code] = true;
                if (code < 128 && code != 34 && code != 38 && code != 60 && code != 62) {
                    noExtra = false;
                }
            }
            special[10] = special[13] = true;
            StringBuilder bits = new StringBuilder();
            for (int word = 0; word < 2048; word++) {
                int mask = 0;
                for (int bit = 0; bit < 32; bit++) {
                    if (special[word * 32 + bit]) mask |= 1 << bit;
                }
                if (mask != 0) {
                    bits.append((char) word).append((char) (mask >>> 16)).append((char) mask);
                }
            }
            StringBuilder ascii = new StringBuilder();
            for (int table = 0; table < 3; table++) {
                for (int word = 0; word < 8; word++) {
                    int mask = 0;
                    for (int bit = 0; bit < 16; bit++) {
                        int c = word * 16 + bit;
                        boolean clean = ((c >= 32 || c == 10 || c == 13 || c == 9)
                                && !special[c]) || c == 34;
                        boolean value = table == 0 ? special[c] : table == 1 ? !clean : clean;
                        if (value) mask |= 1 << bit;
                    }
                    ascii.append((char) mask);
                }
            }
            out.append("\n    // ").append(kind).append("Entities.properties SHA-256: ")
               .append(HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes)))
               .append("\n    private static final class ").append(kind).append(" {\n");
            literal(out, "entities", entities.toString(), 48);
            literal(out, "bits", bits.toString(), 24);
            literal(out, "ascii", ascii.toString(), 24);
            out.append("        static boolean onlyQuotAmpLtGt() { return ").append(noExtra)
               .append("; }\n    }\n");
        }
        Files.writeString(Path.of(args[1]), out.append("}\n"));
    }

    private static void literal(StringBuilder out, String name, String data, int width) {
        out.append("        static String ").append(name).append("() {\n            return ");
        for (int i = 0; i < data.length(); i++) {
            if (i != 0 && i % width == 0) out.append("\"\n                 + \"");
            else if (i == 0) out.append('"');
            char c = data.charAt(i);
            if (c == '"' || c == '\\') out.append('\\').append(c);
            else if (c >= 32 && c < 127) out.append(c);
            else if (c <= 255) out.append(String.format("\\%03o", (int) c));
            else out.append(String.format("\\u%04x", (int) c));
        }
        out.append("\";\n        }\n");
    }
}
