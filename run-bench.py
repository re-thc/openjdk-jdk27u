#!/usr/bin/env python3
import argparse, json, os, subprocess, time
from bench_contract import expected, load, workloads
from pathlib import Path
p = argparse.ArgumentParser()
p.add_argument('--phase', choices=['screen','qualify','tier'], default='screen')
p.add_argument('--config', default='c2-avx2')
p.add_argument('--rounds', type=int, default=5)
p.add_argument('--old-image', help='Preserved pre-refinement image for a direct additional C2 control')
a = p.parse_args()
if a.phase != 'screen' and a.rounds < 5: p.error('qualification requires at least five paired rounds')
root=Path('/workspace/sz-evidence')
out=root/a.phase/a.config
out.mkdir(parents=True, exist_ok=True)
if (out/'RUN.json').exists(): raise SystemExit('Refusing to replace existing study: '+str(out))
images={'base':'/workspace/sz-scans/build/scans/images/jdk/bin/java',
        'candidate':'/workspace/sz-candidate/build/scans/images/jdk/bin/java',
        'off':'/workspace/sz-candidate/build/scans/images/jdk/bin/java'}
labels=['base','candidate','off']
if a.old_image:
    images['old']=str(Path(a.old_image)/'bin/java')
    labels=['base','candidate','old','off']
(out/'RUN.json').write_text(json.dumps(dict(vars(a),labels=labels,images=images),indent=2)+'\n')
flags=['-Xms256m','-Xmx256m','-XX:+UseSerialGC']
flags += ['-XX:UseAVX='+('0' if 'serial' in a.config else '3' if 'avx3' in a.config else '2')]
flags += ['-Xint'] if a.config.startswith('int') else ['-Xbatch','-XX:TieredStopAtLevel=1'] if a.config.startswith('c1') else ['-Xbatch','-XX:-TieredCompilation']
cp='/workspace/sz-evidence/bench-classes:/workspace/sz-evidence/jmh/*'
# Each outer invocation is a fresh JVM with the exact standard JMH compiler
# hints/blackhole flags generated by JMH CompilerHints.addCompilerHints. The
# entire profile-conditioned sweep is the independently repeated unit.
common=['-cp',cp,'org.openjdk.jmh.Main','StringZillaScans','-f','0','-t','1','-wi','2','-w','100ms','-i','3','-r','100ms','-rf','json','-foe','true']
for r in range(a.rounds):
    order=labels if r%2==0 else list(reversed(labels))
    for label in order:
        groups=[('all',[])] if a.phase=='qualify' else [
            ('white',['-p','workload='+','.join(workloads(a.phase,'white')), 'StringZillaScans.(trim|strip|stripLeading|stripTrailing|isBlank)$']),
            ('lines',['-p','workload='+','.join(workloads(a.phase,'lines')), 'StringZillaScans.lines.*'])]
        for group,extra in groups:
            result=out/f'{r:02d}-{label}-{group}.json'
            log=out/f'{r:02d}-{label}-{group}.log'
            hint_label='base' if label=='base' else 'candidate'
            hint_flags=(root/'hints'/f'{hint_label}.flags').read_text().splitlines()
            command=['taskset','-c','1',images[label]]+flags+hint_flags+(['-XX:-UseStringZillaIntrinsics'] if label=='off' else [])+common+['-rff',str(result)]
            if extra:
                command.remove('StringZillaScans')
                command += extra
            event={'round':r,'label':label,'group':group,'command':command,'start':time.time()}
            with (out/'events.jsonl').open('a') as f: f.write(json.dumps(event)+'\n')
            with log.open('w') as f: ret=subprocess.run(command,stdout=f,stderr=subprocess.STDOUT).returncode
            if ret or not result.exists(): raise SystemExit(f'failed {ret}: {log}')
            load(result,expected(a.phase,group))
            for item in json.loads(result.read_text()):
                if any(flag not in item['jvmArgs'] for flag in flags+hint_flags):
                    raise SystemExit('JVM flags not applied: '+str(result))
            output=log.read_text()
            if any(message in output for message in ['Error parsing', 'Could not parse', 'Unrecognized VM option', 'An error occurred during parsing']):
                raise SystemExit('VM hint parsing error: '+str(log))
            print(f'{a.config} round {r+1}/{a.rounds} {label} {group}',flush=True)
